  static Map<String, CertificationDefinition> certificationById() => {for (final d in certificationDefinitions()) d.id: d};

  static Map<String, String> _aliasToIdIndex() {
    final map = <String, String>{};
    for (final d in certificationDefinitions()) {
      final all = <String>[d.displayName, if (d.shortName != null) d.shortName!, ...d.aliases, ...d.searchKeywords];
      for (final a in all) {
        final norm = normalizeCertificationText(a);
        map[norm] = d.id;
      }
    }
    return map;
  }

  static final Map<String, String> _aliasToId = _aliasToIdIndex();

  /// Conservative normalization for matching.
  ///
  /// - lowercase
  /// - replace common separators (/,–,—) with space
  /// - collapse whitespace
  /// - normalize roman numerals I/II/III/IV at token boundaries
  ///
  /// Intentionally NOT fuzzy.
  static String normalizeCertificationText(String input) {
    var s = input.trim().toLowerCase();
    s = s.replaceAll(RegExp(r'[–—/\\]'), ' ');
    s = s.replaceAll(RegExp(r'[^a-z0-9\s-]'), ' ');
    s = s.replaceAll('-', ' ');
    s = s.replaceAll(RegExp(r'\s+'), ' ').trim();

    // Token-level roman numeral normalization.
    final parts = s.split(' ');
    for (var i = 0; i < parts.length; i++) {
      parts[i] = switch (parts[i]) {
        'i' => '1',
        'ii' => '2',
        'iii' => '3',
        'iv' => '4',
        _ => parts[i],
      };
    }
    return parts.join(' ');
  }

  /// Returns a stable CertificationDefinition ID if the input matches a known alias.
  static String? matchCertificationDefinitionId(String userText) {
    final norm = normalizeCertificationText(userText);
    return _aliasToId[norm];
  }

  /// Development-time validation: ensure catalog requirements reference valid IDs.
  static void validateCatalog() {
    final defs = certificationById();
    for (final g in goals()) {
      for (final r in g.requirements) {
        final id = r.certificationDefinitionId;
        if (r.type == RequirementType.certification && id != null && !defs.containsKey(id)) {
          debugPrint('Invalid certificationDefinitionId: $id in requirement ${r.id} (${r.name}).');
        }
      }
    }
  }

